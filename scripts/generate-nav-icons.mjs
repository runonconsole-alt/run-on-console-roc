/**
 * Run On Console — icons for the CMS-editable header menu and footer.
 *
 * Writes the same SVG markup to two places, so the React header/footer and the
 * server (api/v1/cms/site-layer-lib.php, which redraws the menu from the CMS) print
 * exactly the same HTML:
 *   src/data/navIcons.js                              (React)
 *   ROC-Production/upload/api/v1/cms/nav-icons.json   (PHP)
 *
 *   node scripts/generate-nav-icons.mjs
 */
import fs from 'fs';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as L from 'lucide-react';

const ICONS = {
  home: 'Home', cpu: 'Cpu', gamepad: 'Gamepad2', book: 'BookOpen', grid: 'LayoutGrid', info: 'Info', pen: 'PenTool',
  mail: 'Mail', scale: 'Scale', 'file-check': 'FileCheck', compass: 'Compass', handshake: 'Handshake', 'file-text': 'FileText',
  check: 'CheckCircle', shield: 'ShieldCheck', star: 'Star', tag: 'Tag', monitor: 'Monitor', headphones: 'Headphones',
  mouse: 'Mouse', keyboard: 'Keyboard', laptop: 'Laptop', tv: 'Tv', zap: 'Zap', bag: 'ShoppingBag', users: 'Users',
  globe: 'Globe', link: 'Link', heart: 'Heart', flame: 'Flame', trophy: 'Trophy', gift: 'Gift', newspaper: 'Newspaper',
  'arrow-right': 'ArrowRight', 'chevron-down': 'ChevronDown',
};

const out = {};
for (const [key, name] of Object.entries(ICONS)) {
  const C = L[name];
  if (!C) throw new Error('lucide-react has no ' + name);
  // Rendered with a placeholder class; the caller puts its own classes in.
  out[key] = renderToStaticMarkup(React.createElement(C, { className: '__CLS__' }));
}
fs.writeFileSync('src/data/navIcons.js',
  '// Generated by scripts/generate-nav-icons.mjs — do not edit.\n' +
  '// Same markup as ROC-Production/upload/api/v1/cms/nav-icons.json (used by the server).\n' +
  'export const NAV_ICONS = ' + JSON.stringify(out, null, 1) + ';\n');
fs.writeFileSync('ROC-Production/upload/api/v1/cms/nav-icons.json', JSON.stringify(out));
console.log('Nav icons:', Object.keys(out).length);

// The default menu/footer (src/data/siteNav.js) for the server: used when the CMS
// menu is reset, so built pages get the default markup back.
const { DEFAULT_SITE_NAV } = await import('../src/data/siteNav.js');
fs.writeFileSync('ROC-Production/upload/api/v1/cms/nav-default.json', JSON.stringify(DEFAULT_SITE_NAV));
console.log('Default menu written.');
